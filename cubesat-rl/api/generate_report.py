#!/usr/bin/env python3
import sys
import os
import json
import argparse
import tempfile
import matplotlib.pyplot as plt
from fpdf import FPDF
from datetime import datetime

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from db.database import _connect, get_user_by_id, get_mission_profile

def get_comparison(cmp_id: int):
    with _connect() as conn:
        row = conn.execute("SELECT * FROM comparisons WHERE id = ?", (cmp_id,)).fetchone()
        if not row:
            return None
        return dict(row)

def plot_trajectory(ppo_traj, pid_traj, filepath):
    plt.figure(figsize=(8, 4))
    
    ppo_alts = [step.get('alt_km', 0) for step in ppo_traj]
    pid_alts = [step.get('alt_km', 0) for step in pid_traj]
    
    plt.plot(ppo_alts, label="PPO Agent", color="#06b6d4")
    plt.plot(pid_alts, label="PID Baseline", color="#f97316")
    plt.title("Altitude over Time")
    plt.xlabel("Steps")
    plt.ylabel("Altitude (km)")
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(filepath)
    plt.close()

def generate_pdf(cmp_id: int, user_id: int):
    comparison = get_comparison(cmp_id)
    if not comparison:
        print(json.dumps({"ok": False, "error": "Comparison not found"}))
        return
        
    user = get_user_by_id(user_id) if user_id else None
    mission = get_mission_profile(comparison['mission_profile_id']) if comparison.get('mission_profile_id') else None
    
    ppo_traj = json.loads(comparison['ppo_trajectory'])
    pid_traj = json.loads(comparison['pid_trajectory'])
    rec = json.loads(comparison['recommendation']) if comparison.get('recommendation') else None
    verifications = json.loads(comparison['verification_results']) if comparison.get('verification_results') else None

    # Generate Plot
    plot_path = os.path.join(tempfile.gettempdir(), f"plot_{cmp_id}.png")
    plot_trajectory(ppo_traj, pid_traj, plot_path)

    # Create PDF
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, "CubeSat Mission Operations Report", new_x="LMARGIN", new_y="NEXT", align="C")
    
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(0, 8, f"Date: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", new_x="LMARGIN", new_y="NEXT", align="C")
    if user:
        pdf.cell(0, 8, f"Generated by: {user['username']} ({user['role']})", new_x="LMARGIN", new_y="NEXT", align="C")
    pdf.ln(10)
    
    if mission:
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 10, f"Mission Profile: {mission['name']}", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(0, 6, f"Target Altitude: {mission['target_alt_km']} km", new_x="LMARGIN", new_y="NEXT")
        pdf.cell(0, 6, f"Fuel Budget: {mission['fuel_budget_kg']} kg", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(5)

    if rec:
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 10, "Recommendation", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 10)
        pdf.multi_cell(0, 6, f"Winner: {rec['winner'].upper()} (Confidence: {rec['confidence']})", new_x="LMARGIN", new_y="NEXT")
        pdf.multi_cell(0, 6, rec['summary'], new_x="LMARGIN", new_y="NEXT")
        if rec.get('warnings'):
            pdf.set_text_color(220, 38, 38)
            for w in rec['warnings']:
                pdf.multi_cell(0, 6, f"- {w}", new_x="LMARGIN", new_y="NEXT")
            pdf.set_text_color(0, 0, 0)
        pdf.ln(5)

    if verifications and len(verifications) == 2:
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 10, "Requirements Verification", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "B", 10)
        
        # Table Header
        col_w = [80, 55, 55]
        pdf.cell(col_w[0], 8, "Requirement", border=1, align="C")
        pdf.cell(col_w[1], 8, "PPO Agent", border=1, align="C")
        pdf.cell(col_w[2], 8, "PID Baseline", border=1, align="C", new_x="LMARGIN", new_y="NEXT")
        
        pdf.set_font("Helvetica", "", 9)
        ppo_v = next(v['verify'] for v in verifications if v['controller'] == 'ppo')
        pid_v = next(v['verify'] for v in verifications if v['controller'] == 'pid')
        
        if ppo_v.get('requirements') and pid_v.get('requirements'):
            for ppo_req, pid_req in zip(ppo_v['requirements'], pid_v['requirements']):
                pdf.cell(col_w[0], 8, f"{ppo_req['id']}: {ppo_req['name']}", border=1)
                
                ppo_status = "PASS" if ppo_req['passed'] else "FAIL"
                pid_status = "PASS" if pid_req['passed'] else "FAIL"
                
                # We can't easily change text color per cell in fpdf2 without moving cursors, so just print text
                pdf.cell(col_w[1], 8, f"{ppo_status} ({ppo_req['actual']})", border=1, align="C")
                pdf.cell(col_w[2], 8, f"{pid_status} ({pid_req['actual']})", border=1, align="C", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(5)

    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 10, "Trajectory Analysis", new_x="LMARGIN", new_y="NEXT")
    pdf.image(plot_path, x=15, w=180)
    pdf.ln(5)

    # Engineering Disclaimer
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(100, 100, 100)
    pdf.multi_cell(0, 4, "DISCLAIMER: This report is generated by the CubeSat Mission Design & Verification Platform for engineering analysis purposes only. It does not constitute formal flight qualification or certification.", new_x="LMARGIN", new_y="NEXT", align="C")
    pdf.set_text_color(0, 0, 0)
    
    # Save Report
    reports_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'reports')
    os.makedirs(reports_dir, exist_ok=True)
    file_path = os.path.join(reports_dir, f"report_{cmp_id}.pdf")
    pdf.output(file_path)
    
    # Clean up plot
    if os.path.exists(plot_path):
        os.remove(plot_path)

    # Save to DB
    with _connect() as conn:
        cursor = conn.cursor()
        cursor.execute('''
            INSERT INTO reports (user_id, comparison_id, file_path, format, created_at)
            VALUES (?, ?, ?, ?, ?)
        ''', (user_id, cmp_id, file_path, 'pdf', datetime.now().isoformat()))
        conn.commit()
        report_id = cursor.lastrowid
        
    print(json.dumps({
        "ok": True,
        "data": {
            "report_id": report_id,
            "file_path": file_path
        }
    }))

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--comparison_id", type=int, required=True)
    parser.add_argument("--user_id", type=int, required=False, default=None)
    args = parser.parse_args()
    generate_pdf(args.comparison_id, args.user_id)
